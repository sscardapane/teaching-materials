"""Activation scale through a deep ReLU MLP for three initialization scales.

Writes activation-scale.tex, a TikZ figure with the measured values embedded,
so the slide uses the course fonts and colors. Run from this directory:

    python3 plot_activation_scale.py

Setup: L = 20 hidden layers of width D = 512, no biases, ReLU activations,
a batch of 256 standard Gaussian inputs, and weights sampled from
N(0, c / D) with c in {1, 2, 4}. For each layer we record the root mean
square of all hidden activations in the batch. Theory: each layer multiplies
the mean square by c / 2, so c = 2 (He initialization) keeps it constant.
"""

from pathlib import Path

import numpy as np

DEPTH = 20
WIDTH = 512
BATCH = 256
SCALES = [(1, 'drawred', 'densely dashed'), (2, 'darkcerulean', 'solid'),
          (4, 'draworange', 'densely dotted')]
Y_MIN, Y_MAX = -12, 12  # log2 range shown on the plot

rng = np.random.default_rng(0)
x = rng.standard_normal((BATCH, WIDTH))

curves = {}
for c, _, _ in SCALES:
    h = x
    rms = [np.sqrt(np.mean(h ** 2))]
    for _ in range(DEPTH):
        W = rng.normal(0.0, np.sqrt(c / WIDTH), size=(WIDTH, WIDTH))
        h = np.maximum(h @ W.T, 0.0)
        rms.append(np.sqrt(np.mean(h ** 2)))
    curves[c] = np.log2(rms)
    assert Y_MIN < curves[c].min() and curves[c].max() < Y_MAX

# Plot coordinates: layer l -> x = l * SX, log2(rms) -> y = v * SY.
SX, SY = 0.2, 0.135
lines = [
    '% Generated by plot_activation_scale.py; do not edit by hand.',
    '\\begin{tikzpicture}',
    f'  \\draw[drawgray!35] (0,0) -- ({DEPTH * SX:.2f},0);',
    f'  \\draw[->,drawgray] (0,{Y_MIN * SY:.3f}) -- (0,{(Y_MAX + 1) * SY:.3f});',
    f'  \\draw[->,drawgray] (0,{Y_MIN * SY:.3f}) -- ({DEPTH * SX + 0.3:.2f},{Y_MIN * SY:.3f});',
    f'  \\node[font=\\scriptsize] at ({DEPTH * SX / 2:.2f},{Y_MIN * SY - 0.55:.3f}) {{layer $\\ell$}};',
]
for layer in range(0, DEPTH + 1, 5):
    lines.append(f'  \\draw[drawgray] ({layer * SX:.2f},{Y_MIN * SY:.3f}) -- ++(0,-0.06)'
                 f' node[below,font=\\scriptsize] {{${layer}$}};')
for v in range(-10, 11, 5):
    label = '1' if v == 0 else f'2^{{{v}}}'
    lines.append(f'  \\draw[drawgray] (0,{v * SY:.3f}) -- ++(-0.06,0)'
                 f' node[left,font=\\scriptsize] {{${label}$}};')
for c, color, style in SCALES:
    pts = ' '.join(f'({i * SX:.3f},{v * SY:.3f})' for i, v in enumerate(curves[c]))
    lines.append(f'  \\draw[{color},very thick,{style}] plot coordinates {{{pts}}};')
    end = curves[c][-1] * SY
    label = f'{c}/D'
    lines.append(f'  \\node[right,text={color},font=\\scriptsize] at ({DEPTH * SX:.2f},{end:.3f})'
                 f' {{$\\sigma^2={label}$}};')
lines.append('\\end{tikzpicture}')

Path(__file__).with_name('activation-scale.tex').write_text('\n'.join(lines) + '\n')
for c, _, _ in SCALES:
    print(f'c={c}: final rms = 2^{curves[c][-1]:.2f}')
